    <div class="rv mw-66ch"><h2 class="sec-head">Frequently Asked Questions</h2></div>
    <div class="faq rv">
      <details>
        <summary>How long does it take to get ISO certified?</summary>
        <div class="faq-a">The time required to achieve ISO certification depends on your organization's size, complexity, number of locations, existing processes, applicable ISO standard, and level of preparation. A small organization with established processes may be ready within a few weeks to a few months, while larger or more complex organizations can require several months. The typical process includes gap assessment, management-system implementation, documentation, employee awareness, internal audit, management review, corrective actions, and the certification audit.</div>
      </details>
      <details>
        <summary>Which ISO certification is required for government tenders in the GCC?</summary>
        <div class="faq-a">There is no single ISO certification required for every government tender across the GCC. Requirements vary by country, government authority, industry, contract, and tender specifications. ISO 9001 is commonly relevant to quality management, while ISO 14001 and ISO 45001 may be required or requested for environmental and occupational health &amp; safety requirements. For example, Abu Dhabi Judicial Department specifies ISO 9001, ISO 14001 and ISO 45001 for certain high-risk supplier and contractor registrations. Always check the specific prequalification and tender documents before selecting an ISO standard.</div>
      </details>
      <details>
        <summary>Can a small business or startup get ISO certified?</summary>
        <div class="faq-a">Yes. ISO management-system standards can be implemented by organizations of different sizes and across many sectors. ISO specifically provides guidance for SMEs implementing ISO 9001, and the current ISO 9001:2026 requirements are applicable to organizations of all sizes and sectors. The scope and documentation can be tailored to the organization's actual activities, size, processes, risks, and applicable requirements.</div>
      </details>
      <details>
        <summary>What documents are required for ISO certification?</summary>
        <div class="faq-a">The required documented information depends on the ISO standard and your organization's scope. Depending on the standard, documentation may include policies, objectives, procedures, process records, risk assessments, registers, training records, operational records, internal audit results, management-review records, corrective-action records, and other evidence demonstrating that the management system is implemented and maintained. A gap assessment can identify what your organization already has and what needs to be developed before the certification audit.</div>
      </details>
      <details>
        <summary>How do I choose an accredited ISO certification body?</summary>
        <div class="faq-a">Choose a certification body that is competent for your applicable ISO standard and industry scope and verify its accreditation status with the relevant national accreditation body or through IAF CertSearch where applicable. ISO recommends evaluating certification bodies, checking whether they use the relevant conformity-assessment requirements, and verifying accreditation. Remember that ISO itself does not issue certificates; certification is performed by independent certification bodies.</div>
      </details>
      <details>
        <summary>How much does ISO certification cost?</summary>
        <div class="faq-a">ISO certification costs depend on the standard, organization size, number of employees and locations, scope, complexity, consultant involvement, and certification-body audit fees. A proper quotation should consider both implementation and independent certification costs.</div>
      </details>
      <details>
        <summary>Can an ISO consultant help us prepare for the certification audit?</summary>
        <div class="faq-a">Yes. An ISO Certification Consultant can assist with gap assessment, management-system implementation, documentation, risk assessment, employee awareness, internal audit preparation, management review, corrective actions, and certification-audit readiness. The final certification decision, however, is made by the independent certification body.</div>
      </details>
